# SECTION 3: DEFINE HELPER FUNCTION - SELECT BEST N INJECTIONS
# ============================================================================
# This function finds the N injections with the lowest coefficient of
# variation (most similar to each other), which tends to give the most
# reliable mean estimate

#' Select measurements with lowest coefficient of variation
#'
#' Given a vector of measurements, returns the subset of n measurements
#' with the lowest CV among all possible combinations.
#'
#' PURPOSE:
#'   When you have replicate measurements and want to identify the most
#'   consistent subset (e.g., the 3 most similar out of 5 replicates),
#'   this function finds the combination with lowest CV.
#'
#' PARAMETERS:
#'   measurements (numeric vector): All available measurements
#'   n (integer): Number of measurements to select (default: 3)
#'
#' RETURNS:
#'   (numeric vector): The n measurements with lowest CV among all combinations
#'
#' EXAMPLE:
#'   measurements <- c(100.1, 100.2, 100.3, 95.5, 100.4)
#'   best <- select_lowest_cv(measurements, n = 3)
#'   # Returns: 100.1, 100.2, 100.3 (ignoring the outlier 95.5)

select_lowest_cv <- function(measurements, n = 3) {
  
  # Remove NA values
  measurements <- measurements[!is.na(measurements)]
  
  # Check if we have enough measurements
  if (length(measurements) < n) {
    warning(paste0(
      "Only ", length(measurements),
      " valid measurements found, returning all (needed ", n, ")"
    ))
    return(measurements)
  }
  
  # Generate all possible combinations of n measurements
  # For example, with 5 measurements and n=3, generates C(5,3)=10 combinations
  combos <- combn(measurements, n, simplify = FALSE)
  
  # Calculate CV for each combination
  # CV = (standard deviation / mean) * 100
  cvs <- sapply(combos, function(x) {
    if (mean(x) == 0) {
      # Avoid division by zero
      return(Inf)
    }
    return((sd(x) / mean(x)) * 100)
  })
  
  # Select the combination with the lowest CV
  best_combo <- combos[[which.min(cvs)]]
  
  return(best_combo)
}

