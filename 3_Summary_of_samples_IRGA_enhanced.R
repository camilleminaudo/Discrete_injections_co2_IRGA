# PURPOSE:
#   This script compiles ppm data from all injection replicates across
#   all samples and dates, and produces summary tables with:
#   1. Mean, SD, and count for each sample using ALL injections
#   2. Mean, SD, and count for each sample using BEST 3 injections
#   3. Full injection-level data for further analysis
#
#   The script intelligently decides whether to use all injections or
#   discard outliers based on whether the coefficient of variation (CV)
#   improves when using only the best N injections.
#
# INPUT FILES:
#   ppm_samples_CO2_*.csv
#   (Generated by Script 2)
#
# OUTPUT FILES GENERATED:
#   1. All_Summary_co2_allinjections.csv
#      - Summary using all available injections
#      - Columns: dayofanalysis, sample, avg_ppm, sd_ppm, n_used, n_discarded
#
#   2. All_Summary_co2_best3inj.csv
#      - Summary using best 3 injections (if CV improves)
#      - Columns: dayofanalysis, sample, avg_ppm, sd_ppm, n_used, n_discarded
#
#   3. All_Injections_ppm_co2.csv
#      - Individual ppm for every single injection
#      - Useful for quality control and further analysis
#
# CV-BASED FILTERING LOGIC:
#   For each sample:
#     1. Calculate CV using all N injections
#     2. Calculate CV using best 3 injections (if N >= 3)
#     3. If CV(best 3) < CV(all), report the best 3 mean/SD
#     4. Otherwise, report the all-injections mean/SD
#   This approach automatically detects and minimizes the impact of
#   outlier measurements while maintaining transparency about which
#   were discarded.
#
# ============================================================================

