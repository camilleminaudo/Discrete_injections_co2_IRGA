message("[Script 3] Found ", length(co2_ppm_files), " ppm file(s)")

# Read and combine all ppm files
co2 <- NULL

for (i in co2_ppm_files) {
  message("  - Reading: ", basename(i))
  
  file_data <- tryCatch({
    read_csv(i, show_col_types = FALSE)
  }, error = function(e) {
    warning("Error reading file: ", i, " - ", e$message)
    return(NULL)
  })
  
  if (!is.null(file_data)) {
    if (is.null(co2)) {
      co2 <- file_data
    } else {
      co2 <- rbind(co2, file_data)
    }
  }
}

if (is.null(co2) || nrow(co2) == 0) {
  stop("ERROR: No ppm data successfully read from files")
}

# Convert to data frame and ensure data types are correct
co2 <- as.data.frame(co2)

message("[Script 3] Total ppm records compiled: ", nrow(co2))
message("[Script 3] Date range: ",
        format(min(as.Date(co2$dayofanalysis), na.rm = TRUE), "%d-%b-%Y"),
        " to ",
        format(max(as.Date(co2$dayofanalysis), na.rm = TRUE), "%d-%b-%Y"))

# ============================================================================
# SECTION 5: CALCULATE STATISTICS WITH ALL INJECTIONS
# ============================================================================
# Group by sample and day, calculate mean, SD, and count

message("\n[Script 3] ========== Calculating Statistics ==========")
message("[Script 3] Method 1: Using ALL injections")

all_injections_summary <- co2 %>%
  group_by(gas, sample, dayofanalysis) %>%
  summarise(
    avg_ppm = mean(ppm, na.rm = TRUE),
    sd_ppm = sd(ppm, na.rm = TRUE),
    cv = (sd_ppm / avg_ppm) * 100,  # Coefficient of variation as percentage
    n_all = sum(!is.na(ppm)),       # Number of injections
    .groups = "drop"
  )

message("[Script 3]   - ", nrow(all_injections_summary), 
        " unique sample-day combinations")

# ============================================================================
# SECTION 6: CALCULATE STATISTICS WITH BEST 3 INJECTIONS
# ============================================================================
# For samples with 3+ injections, select the best 3 and recalculate

message("[Script 3] Method 2: Using best 3 injections (if n >= 3)")

best3_summary <- co2 %>%
  group_by(gas, sample, dayofanalysis) %>%
  # First check: only proceed if we have at least 3 injections
  mutate(
    total_injections = sum(!is.na(ppm))
  ) %>%
  filter(total_injections >= 3) %>%
  # Apply the selection function to each group
  reframe(
    ppm_selected = select_lowest_cv(ppm, n = 3)
  ) %>%
  # Calculate statistics on the selected subset
  group_by(gas, sample, dayofanalysis) %>%
  summarise(
    avg_ppm_best3 = mean(ppm_selected),
    sd_ppm_best3 = sd(ppm_selected),
    cv_best3 = (sd_ppm_best3 / avg_ppm_best3) * 100,
    n_best3 = sum(!is.na(ppm_selected)),
    .groups = "drop"
  )

message("[Script 3]   - ", nrow(best3_summary),
        " samples eligible for CV-based filtering (n >= 3)")

# ============================================================================
# SECTION 7: COMBINE AND DECIDE WHICH TO USE
# ============================================================================
# For each sample, determine whether using best 3 injections improves CV

message("[Script 3] Comparing CV between all and best 3 injections")

final_summary <- all_injections_summary %>%
  left_join(best3_summary, by = c("gas", "sample", "dayofanalysis")) %>%
  # Flag whether discarding improved CV
  mutate(
    improved_cv = if_else(
      is.na(cv_best3),
      FALSE,                         # Can't compare if no best3 available
      cv_best3 < cv                  # TRUE if best3 CV is lower
    ),
    # Choose between all and best3 based on CV improvement
    avg_ppm = if_else(improved_cv, avg_ppm_best3, avg_ppm),
    sd_ppm = if_else(improved_cv, sd_ppm_best3, sd_ppm),
    n_used = if_else(improved_cv, n_best3, n_all),
    n_discarded = if_else(improved_cv, n_all - n_best3, 0)
  ) %>%
  # Select final output columns
  select(
    gas, sample, dayofanalysis,
    avg_ppm, sd_ppm, n_used, n_discarded
  ) %>%
  # Sort by date and sample name for readability
  arrange(dayofanalysis, sample)

# Log summary of CV-based filtering
n_filtered <- sum(final_summary$n_discarded > 0, na.rm = TRUE)

if (n_filtered > 0) {
  message("[Script 3] CV-based filtering applied to ", n_filtered, 
          " samples")
  message("[Script 3] (improved CV by using best 3 injections)")
}

