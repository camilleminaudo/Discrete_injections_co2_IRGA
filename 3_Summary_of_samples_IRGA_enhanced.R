# Compile all ppm measurements from all samples and dates

message("\n[Script 3] ========== Importing ppm Data ==========")

# Locate all ppm files
co2_ppm_files <- list.files(
  folder_results,
  pattern = "^ppm_samples_CO2",
  recursive = TRUE,
  full.names = TRUE
)

if (length(co2_ppm_files) == 0) {
  stop("ERROR: No ppm_samples_CO2 files found in ", folder_results,
       "\nDid you run Scripts 1 and 2 first?")
